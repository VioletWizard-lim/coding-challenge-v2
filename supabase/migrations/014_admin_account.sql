-- 014: 관리자 계정 만들기 (v2 전용, 한 번만)
--
-- 관리자(role='admin')는 v2의 🛠 관리자 페이지(/admin)로만 들어가요. 교사 계정 추가·비밀번호 초기화, 서비스 상태를 봐요.
-- v1은 로그인할 때 역할을 고르기 때문에 admin 계정으로는 v1에 들어갈 수 없어요(v1 동작은 그대로).
-- 표·칸은 바꾸지 않고 users에 한 줄만 더해요.
--
-- 실행 방법: 아래 세 값을 바꾼 뒤 Supabase 대시보드 → SQL Editor에서 Run
--   - 'admin' : 관리자 아이디 (학생·교사 아이디와 겹치지 않게)
--   - '관리자' : 화면에 보일 이름
--   - '여기에-임시-비밀번호' : 처음 로그인할 비밀번호
-- 처음 로그인하면 v2가 비밀번호를 암호화(bcrypt)해 저장하고 평문 비밀번호는 지워요.
-- 이 SQL을 저장소나 메신저에 비밀번호가 적힌 채로 남기지 마세요.

insert into users (id, password, role, name)
values ('admin', '여기에-임시-비밀번호', 'admin', '관리자')
on conflict (id) do nothing;

-- 만약 "role" 칸에 허용 값 제한이 걸려 있어 오류가 나면, 실행하지 말고 알려 주세요(기존 제한은 바꾸지 않아요).
