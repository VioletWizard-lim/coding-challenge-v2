-- 교사가 문제(번호, 제목, 설명, 시작 코드)를 미리 올리고 공개 시각(open_at)을 정한다.
--   open_at이 비어 있으면 비공개, 정해져 있으면 그 시각부터 학생에게 보인다.
-- 이 SQL을 실행하기 전에는 v2가 코드에 들어 있는 문제 목록을 그대로 쓴다.

create table if not exists problems (
  id bigint generated always as identity primary key,
  subject text not null,
  number text not null,
  title text not null,
  description text not null default '',
  starter_code text not null default '',
  open_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (subject, number)
);

-- 보안 잠금(RLS)을 켜 둔다. v2 서버는 서버 전용 키로 접근하므로 영향 없고,
-- 공개 전 문제를 다른 키(anon)로 미리 볼 수 없게 된다.
alter table problems enable row level security;

