const INFORMATICS: Record<string, string> = Object.fromEntries(
  Array.from({ length: 9 }, (_, i) => [1, 2, 3].map((j) => `${i + 1}-${j}`))
    .flat()
    .map((p) => [p, p]),
);

export const SUBJECTS: Record<string, Record<string, string>> = {
  프로그래밍: PROGRAMMING,
  정보: INFORMATICS,
};

/** 학생 계정의 subjects("프로그래밍,정보")에서 쓸 수 있는 과목만 고른다. 없으면 전체 (v1과 같음). */
export function allowedSubjects(subjects: string | null | undefined): string[] {
  const list = (subjects ?? "")
    .split(",")
    .map((s) => s.trim())
    .filter((s) => s in SUBJECTS);
  return list.length ? list : Object.keys(SUBJECTS);
}

/** 선택 목록에 보일 이름: "2-3. 내가 가진 용돈 확인하기" (이름이 번호와 같으면 번호만) */
export const problemLabel = (subject: string, problem: string) => {
  const name = SUBJECTS[subject]?.[problem];
  return !name || name === problem ? problem : `${problem}. ${name}`;
};
